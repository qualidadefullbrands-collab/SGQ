import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

const source=(path)=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const app=source('src/App.tsx')
const mobile=source('src/mobile/MobileFotos.tsx')
const css=source('src/mobile/MobileFotos.css')
const api=source('backend/Sgq.Api/Program.cs')

test('phone automatically opens a dedicated photo-only screen without QR codes',()=>{
 assert.match(app,/const MobileFotos=lazy\(\(\)=>import\('\.\/mobile\/MobileFotos'\)\)/)
 assert.match(app,/matchMedia\('\(max-width: 768px\)'\)/)
 assert.match(app,/tab==='fotos-mobile'/)
 assert.match(app,/<MobileFotos processes=\{processes\} inspections=\{inspections\}/)
 assert.doesNotMatch(mobile,/QrCode|qr_token|scan QR/i)
 assert.match(mobile,/Processos com inspeções/)
 assert.doesNotMatch(mobile,/COLETA DE EVIDÊNCIAS/i)
})
test('mobile lists open and started inspections associated with operational processes',()=>{
 assert.match(mobile,/\['aberta','em_andamento'\]\.includes\(i\.status\)/)
 assert.match(mobile,/const valid=new Set\(processes\.map\(p=>p\.id\)\)/)
 assert.match(mobile,/active:processes\.filter\(p=>map\.has\(p\.id\)\)/)
 assert.match(mobile,/selectProcess\(p\.id\)/)
 assert.doesNotMatch(mobile,/list\.length===1/)
 assert.match(mobile,/sgq-photo-not-started/)
})
test('camera and gallery can save large mobile photo batches without mandatory captions',()=>{
 assert.match(mobile,/capture="environment"/)
 assert.match(mobile,/accept="image\/\*"/)
 assert.match(mobile,/multiple onChange=/)
 assert.match(mobile,/photo\.legenda\.trim\(\)/)
 assert.match(mobile,/supabase\.storage\.from\('inspecao-fotos'\)\.upload/)
 assert.match(mobile,/\/fotos\/registrar/)
 assert.doesNotMatch(mobile,/upsert:true/)
 assert.match(mobile,/already exists\|duplicate\|resource already exists\|409/)
 assert.match(mobile,/createImageBitmap/)
})
test('mobile does not contain inspection completion or mutation of measurements',()=>{
 assert.doesNotMatch(mobile,/\/concluir|\/iniciar|\/dimensionais|\/testes|\/amostragem|\/retencao/)
 assert.match(mobile,/A conclusão será feita no computador/)
 assert.match(mobile,/canWrite/)
})
test('API uses a lightweight read endpoint and rejects archived or finished inspections',()=>{
 assert.match(api,/MapGet\("\/api\/mobile\/fotos\/inspecoes\/\{id\}"/)
 assert.match(api,/status is not \("aberta" or "em_andamento"\)/)
 assert.match(api,/Processo arquivado ou indisponível/)
 const upload=api.slice(api.indexOf('app.MapPost("/api/inspecoes/{id}/fotos/registrar"'),api.indexOf('app.MapPost("/api/inspecoes/{id}/laudo"'))
 assert.match(upload,/excluido_em=is\.null/)
 assert.match(upload,/record\.GetProperty\("status"\)\.GetString\(\) is not \("aberta" or "em_andamento"\)/)
 assert.match(upload,/photo\.StoragePath\.StartsWith\(id\+"\/gerais\/"/)
 assert.match(upload,/storage_path=eq\./)
})
test('desktop has a manual lightweight refresh to receive photos captured on phone',()=>{
 assert.match(app,/async function refreshInspectionPhotoEvidence\(\)/)
 assert.match(app,/\/api\/mobile\/fotos\/inspecoes\//)
 assert.match(app,/Atualizar fotos/)
 assert.match(app,/current\?\.id===id/)
})
test('mobile photo styles are scoped and responsive',()=>{
 assert.match(css,/\.sgq-mobile-photo/)
 assert.match(css,/@media\(max-width:360px\)/)
 assert.match(css,/grid-template-columns/)
 assert.match(css,/min-height:100dvh/)
})

test('photo cards visibly identify started versus not started inspections',()=>{
 assert.match(mobile,/sgq-photo-started/)
 assert.match(mobile,/sgq-photo-not-started/)
 assert.match(mobile,/Não iniciada/)
 assert.match(css,/\.sgq-mobile-process\.sgq-photo-started/)
 assert.match(css,/\.sgq-mobile-process\.sgq-photo-not-started/)
})

test('mobile batch queue is bounded, concurrent and caption-free',()=>{
 assert.match(mobile,/pending\.length\+arr\.length>60/)
 assert.match(mobile,/Math\.min\(3,batch\.length\)/)
 assert.match(mobile,/sgq-mobile-batch-grid/)
 assert.match(mobile,/Selecionar várias/)
 assert.match(mobile,/compressed\(photo\.file\)/)
 assert.match(mobile,/queuePhotoOffline\(photo,inspectionId\)/)
 assert.doesNotMatch(mobile,/Informe a legenda de cada foto/)
 assert.doesNotMatch(mobile,/<textarea/)
})
test('server accepts captionless photos and supports safe later desktop editing',()=>{
 const upload=api.slice(api.indexOf('app.MapPost("/api/inspecoes/{id}/fotos/registrar"'),
   api.indexOf('app.MapPut("/api/inspecoes/{id}/fotos/{photoId}/legenda"'))
 assert.match(upload,/if\(string\.IsNullOrWhiteSpace\(photo\.StoragePath\)\)continue/)
 assert.doesNotMatch(upload,/string\.IsNullOrWhiteSpace\(photo\.Legenda\)\)continue/)
 assert.match(upload,/legenda=string\.IsNullOrWhiteSpace\(photo\.Legenda\)\?null:photo\.Legenda\.Trim\(\)/)
 assert.match(api,/app\.MapPut\("\/api\/inspecoes\/\{id\}\/fotos\/\{photoId\}\/legenda"/)
 assert.match(api,/PhotoCaptionRequest/)
 assert.match(api,/photoId/)
 assert.match(app,/async function savePhotoCaption\(photoId:string,currentCaption:string\)/)
 assert.match(app,/Adicionar legenda/)
 assert.match(app,/setEditingPhotoCaptionId\(p\.id\)/)
 assert.match(app,/activeStage==='fotos'/)
 assert.match(api,/documento_gerado_em=\(DateTimeOffset\?\)null/)
})
