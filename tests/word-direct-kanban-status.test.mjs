import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const source=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
const app=source('src/App.tsx')
const api=source('backend/Sgq.Api/Program.cs')
const docs=source('server/app.py')
const board=source('src/components/InspectionsKanban.tsx')
const css=source('src/components/InspectionsKanban.css')
const style=source('src/styles.css')
function part(s,from,to){
 const start=s.indexOf(from),end=s.indexOf(to,start+from.length)
 assert.ok(start>=0&&end>start,'Missing '+from+' / '+to)
 return s.slice(start,end)
}

test('inspection Word renders directly without Storage upload or database persistence',()=>{
 const generate=part(docs,'@app.get("/generate-inspection/{inspection_id}")','@app.get("/template-status")')
 assert.match(generate,/docx=generate_inspection\(template_bytes,payload\)/)
 assert.match(generate,/return Response\(/)
 assert.match(generate,/Content-Disposition/)
 assert.match(generate,/X-SGQ-File-Name/)
 assert.doesNotMatch(generate,/storage_upload\(|storage_path=f|await client\.patch\(|await client\.post\(|"laudos"/)
})
test('API Word download bypasses cached Storage key and verifies genuine DOCX bytes',()=>{
 const download=part(api,'app.MapPost("/api/inspecoes/{id}/laudo"','// Optional Power Automate delivery')
 assert.match(download,/generate-inspection/)
 assert.match(download,/ReadAsByteArrayAsync\(\)/)
 assert.match(download,/bytes\[0\]!=0x50/)
 assert.match(download,/Results\.File\(bytes,contentType,fileName\)/)
 assert.match(api,/\.WithExposedHeaders\("Content-Disposition"\)/)
 assert.match(app,/response\.headers\.get\('content-disposition'\)/)
 assert.doesNotMatch(download,/storage\/v1\/object|\/laudos\//)
 assert.doesNotMatch(download,/documento_gerado_em/)
 const send=part(api,'app.MapPost("/api/inspecoes/{id}/enviar-automate"','app.MapPost("/api/inspecoes/{id}/retencao"')
 assert.match(send,/generate-inspection/)
 assert.match(send,/contentBase64=Convert\.ToBase64String\(bytes\)/)
 assert.match(send,/laudo_id=\(string\?\)null/)
 assert.match(send,/storage_path=\(string\?\)null/)
})
test('Word spinner is visible through download and dismissed on all exits',()=>{
 const fn=part(app,'async function downloadInspectionWord()','if (!sessionReady)')
 assert.match(fn,/setWordDownloading\(true\)/)
 assert.match(fn,/finally\s*\{\s*setWordDownloading\(false\)/)
 assert.match(fn,/const blob=await response\.blob\(\)/)
 assert.match(fn,/link\.click\(\)/)
 assert.doesNotMatch(fn,/armazenado no SGQ/)
 assert.match(app,/aria-label="Gerando Word"/)
 assert.match(app,/sgq-word-spinner/)
 assert.match(style,/\.sgq-word-loading/)
})
test('dragging only moves between queued and in progress, not completed or cancelled',()=>{
 const reverse=part(api,'app.MapPost("/api/inspecoes/{id}/voltar-nao-iniciada"','app.MapGet("/api/amostragem/plano"')
 assert.match(reverse,/status=eq\.em_andamento/)
 assert.match(reverse,/new \{status="aberta",iniciada_em=\(DateTimeOffset\?\)null\}/)
 assert.match(reverse,/status=in\.\(em_andamento,concluida\)/)
 assert.match(reverse,/return Results\.Ok/)
 assert.match(board,/onDragStart=/)
 assert.match(board,/onDrop=/)
 assert.match(board,/const canMoveCard=/)
 assert.match(board,/onMove\?\.\(id,target\)/)
 assert.match(app,/target==='em_andamento'\?'iniciar':'voltar-nao-iniciada'/)
 assert.match(board,/disabled=\{!!movingInspectionId\}/)
 assert.doesNotMatch(board,/label:'Canceladas'/)
})
