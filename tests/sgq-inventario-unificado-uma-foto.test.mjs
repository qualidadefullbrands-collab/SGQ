import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const file=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const ui=file('src/stock/BlindInventoryUnified.tsx')
const app=file('src/App.tsx')
const sql=file('supabase/migrations/20261113180000_sgq_inventario_fluxo_unico_fotos.sql')
const remote=file('supabase/functions/sgq-inventario-foto-direta/index.ts')
const fst=file('supabase/functions/sgq-omie-fst/index.ts')

test('SGQ uses only one unified inventory screen',()=>{
 assert.match(app,/import BlindInventoryUnified/)
 assert.match(app,/stockMode==='cego'&&<BlindInventoryUnified/)
 for(const part of ['1. Localização','2. Processo FST','3. Selecione o produto','4. Quantidade e foto'])assert.ok(ui.includes(part))
 assert.doesNotMatch(ui,/Ver excluídos|showDeleted|setShowDeleted/)
})
test('inventory allows selecting or creating a street or cabinet',()=>{
 assert.match(ui,/localizacoes_estoque/)
 assert.match(ui,/Nova localização/)
 assert.match(ui,/Cadastrar e selecionar/)
 assert.match(sql,/sgq_inventory_locations_insert/)
 assert.match(sql,/sgq_inventory_locations_select/)
})
test('FST lookup includes Omie invoice, fiscal date and customer validation',()=>{
 assert.match(ui,/sgq-omie-fst/)
 assert.match(ui,/modo:'nfe'/)
 assert.match(ui,/Cliente/)
 assert.match(ui,/NF de entrada/)
 assert.match(ui,/Data da NF/)
 assert.match(ui,/Confirmar dados e iniciar contagem/)
 assert.match(ui,/!products.length/)
 assert.match(fst,/dataRegistro:/)
 assert.match(fst,/dataEmissao:/)
})
test('one image per SKU count, immediately transmitted to Omie',()=>{
 assert.match(ui,/const \[photo,setPhoto\]=useState<File\|null>\(null\)/)
 assert.doesNotMatch(ui,/multiple[= ]/)
 assert.match(ui,/Salvar e próximo item/)
 assert.match(ui,/onClick=\{\(\)=>void save\(false\)\}/)
 assert.match(ui,/onClick=\{\(\)=>void save\(true\)\}/)
 assert.match(ui,/functions\.invoke\('sgq-inventario-foto-direta'/)
 assert.doesNotMatch(ui,/window\.confirm\('Contagem registrada\. Deseja ir para o próximo item/)
 assert.match(ui,/resetItem\(delivered\)/)
 assert.match(sql,/sgq_blind_photo_one_per_item/)
 assert.match(remote,/ConsultarProduto/)
 assert.match(remote,/AlterarProduto/)
 assert.match(remote,/item\.codigo_omie/)
 assert.match(remote,/already_synced:true/)
 assert.match(remote,/originals\.some/)
 assert.match(remote,/sgq_inventario_cego_foto_logs/)
})
test('returning to a process shows already counted items and photo retry',()=>{
 assert.match(ui,/loadCounts\(code\)/)
 assert.match(ui,/Já contado nesta localização/)
 assert.match(ui,/Já contado em outra localização/)
 assert.match(ui,/Reenviar foto/)
 assert.match(ui,/setCountedBySku|countedBySku/)
 assert.match(sql,/sgq_inventario_cego_documentos/)
})

test('Omie items do not wait for paginated NF-e search',()=>{
 assert.match(ui,/const receiptJob=authClient\.functions\.invoke\('sgq-omie-fst'/)
 assert.match(ui,/void receiptJob\.then/)
 assert.match(ui,/setProducts\(\[\.\.\.list\.values\(\)\]/)
 assert.match(ui,/nfLoading\?'consultando recebimentos no Omie/)
 assert.match(ui,/lookupRevision\.current/)
})
